import { StrikeGexDetail, BuildUpType, StrikeOiVelocityDetail, OiVelocityResult } from './types';

/**
 * Classifies options market participant flow based on price change and open interest change.
 */
export function classifyBuildUp(priceChange: number, oiChange: number): BuildUpType {
  // Ignore minor noise (less than 100 contracts change)
  if (Math.abs(oiChange) < 100) {
    return 'NEUTRAL';
  }

  if (priceChange > 0 && oiChange > 0) {
    return 'LONG_BUILDUP';
  }
  if (priceChange < 0 && oiChange > 0) {
    return 'SHORT_BUILDUP';
  }
  if (priceChange < 0 && oiChange < 0) {
    return 'LONG_UNWINDING';
  }
  if (priceChange > 0 && oiChange < 0) {
    return 'SHORT_COVERING';
  }

  // If price change is exactly 0 but OI shifted significantly
  if (priceChange === 0) {
    return oiChange > 0 ? 'SHORT_BUILDUP' : 'SHORT_COVERING';
  }

  return 'NEUTRAL';
}

/**
 * Calculates strike-level Open Interest shifts (ΔOI) and Intraday Gamma Velocity (ΔGEX).
 */
export function calculateStrikeOiVelocity(
  strikes: StrikeGexDetail[],
  spot: number,
  lotSize: number
): OiVelocityResult {
  if (!strikes || strikes.length === 0 || spot <= 0 || lotSize <= 0) {
    return {
      totalCallOiChange: 0,
      totalPutOiChange: 0,
      netIntradayDeltaGexCr: 0,
      dominantFlow: 'NEUTRAL',
      topCallAccumulationStrike: 0,
      topPutAccumulationStrike: 0,
      strikeDetails: [],
    };
  }

  let totalCallOiChange = 0;
  let totalPutOiChange = 0;
  let totalNetDeltaGexCr = 0;

  let maxCallOiChange = -Infinity;
  let topCallStrike = strikes[0]?.strikePrice ?? 0;

  let maxPutOiChange = -Infinity;
  let topPutStrike = strikes[0]?.strikePrice ?? 0;

  const flowCounts: Record<BuildUpType, number> = {
    LONG_BUILDUP: 0,
    SHORT_BUILDUP: 0,
    LONG_UNWINDING: 0,
    SHORT_COVERING: 0,
    NEUTRAL: 0,
  };

  const strikeDetails: StrikeOiVelocityDetail[] = strikes.map((s) => {
    // Resolve ΔOI
    const callOiChange =
      s.callChangeOi !== undefined
        ? s.callChangeOi
        : s.callPrevOi !== undefined
        ? s.callOi - s.callPrevOi
        : 0;

    const putOiChange =
      s.putChangeOi !== undefined
        ? s.putChangeOi
        : s.putPrevOi !== undefined
        ? s.putOi - s.putPrevOi
        : 0;

    const callPriceChange = s.callPriceChange ?? 0;
    const putPriceChange = s.putPriceChange ?? 0;

    const callBuildUp = classifyBuildUp(callPriceChange, callOiChange);
    const putBuildUp = classifyBuildUp(putPriceChange, putOiChange);

    flowCounts[callBuildUp]++;
    flowCounts[putBuildUp]++;

    // Intraday Gamma Velocity generated by this session's OI change
    // Formula: Gamma * ΔOI * LotSize * Spot^2 * 0.01 / 1e7
    const callDeltaGexRupees = (s.callGamma ?? 0) * callOiChange * lotSize * spot * spot * 0.01;
    const putDeltaGexRupees = -(s.putGamma ?? 0) * putOiChange * lotSize * spot * spot * 0.01;

    const callDeltaGexCr = Number((callDeltaGexRupees / 1e7).toFixed(2));
    const putDeltaGexCr = Number((putDeltaGexRupees / 1e7).toFixed(2));
    const netDeltaGexCr = Number((callDeltaGexCr + putDeltaGexCr).toFixed(2));

    totalCallOiChange += callOiChange;
    totalPutOiChange += putOiChange;
    totalNetDeltaGexCr += netDeltaGexCr;

    if (callOiChange > maxCallOiChange) {
      maxCallOiChange = callOiChange;
      topCallStrike = s.strikePrice;
    }

    if (putOiChange > maxPutOiChange) {
      maxPutOiChange = putOiChange;
      topPutStrike = s.strikePrice;
    }

    return {
      strikePrice: s.strikePrice,
      callOi: s.callOi,
      putOi: s.putOi,
      callOiChange,
      putOiChange,
      callBuildUp,
      putBuildUp,
      callDeltaGexCr,
      putDeltaGexCr,
      netDeltaGexCr,
    };
  });

  // Determine dominant flow
  let dominantFlow: BuildUpType = 'NEUTRAL';
  let highestCount = 0;
  for (const [flow, count] of Object.entries(flowCounts)) {
    if (flow !== 'NEUTRAL' && count > highestCount) {
      highestCount = count;
      dominantFlow = flow as BuildUpType;
    }
  }

  return {
    totalCallOiChange,
    totalPutOiChange,
    netIntradayDeltaGexCr: Number(totalNetDeltaGexCr.toFixed(2)),
    dominantFlow,
    topCallAccumulationStrike: topCallStrike,
    topPutAccumulationStrike: topPutStrike,
    strikeDetails,
  };
}
